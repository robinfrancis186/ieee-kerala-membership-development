export function filterOpportunities(items, { category = "all", query = "", travelOnly = false } = {}) {
  const term = query.trim().toLocaleLowerCase();
  return items.filter((item) => {
    const inCategory = category === "all"
      || (category === "open" && item.status === "open")
      || (category === "recurring" && item.recurring)
      || (category === "closed" && item.status === "closed")
      || (category === "check" && item.status === "check");
    const searchable = [item.title, item.type, item.organization, item.amount, item.window, item.fit, item.eligibility].join(" ").toLocaleLowerCase();
    return inCategory && (!travelOnly || item.travel) && (!term || searchable.includes(term));
  });
}

export function estimateStudentBranchRebate(memberCount) {
  const count = Number(memberCount);
  if (!Number.isSafeInteger(count) || count < 12 || count > 100000) return null;
  return (count >= 50 ? 100 : 50) + count * 2;
}
